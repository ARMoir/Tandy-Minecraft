"""Bake legible 16-color block art; no RGB conversion/noise generation on DOS."""
from pathlib import Path
import random

def tile(material, face):
    r = random.Random(material * 101 + face)
    base = {0:11,1:7,2:10 if face==0 else 6,3:6,4:7,5:6,6:6,7:2}[material]
    a = [base] * 256
    # Broad clusters survive the CRT; avoid single-pixel checkerboard dithering.
    grain = {0:11,1:8,2:2 if face==0 else 8,3:8,4:8,5:14,6:14,7:10}[material]
    for _ in range(9 if material==7 else (2 if material in (5,6) else 5)):
        x,y=r.randrange(2,13),r.randrange(2,13)
        for yy in range(y,y+2):
            for xx in range(x,x+3):a[yy*16+xx]=grain
    if material==2 and face!=0:
        for x in range(16):
            for y in range(2+(x//3)%2):a[y*16+x]=10 if face==1 else 2
    if material in (4,5):
        for y in (0,8):
            for x in range(16):a[y*16+x]=14 if material==5 else 8
        for y in range(16):a[y*16+(0 if y<8 else 8)]=6 if material==5 else 8
    if material==6:
        if face==0:
            for y in range(3,13):
                for x in range(3,13):
                    if x in (3,12) or y in (3,12):a[y*16+x]=14
        else:
            for y in range(16):
                for x in (3,10):a[y*16+x]=8
    # Restrained seams establish the unit cube grid without black wireframes.
    edge={0:11,1:8,2:2 if face==0 else 6,3:6,4:8,5:6,6:8,7:2}[material]
    for n in range(16):a[n]=edge;a[n*16]=edge
    if face==2:
        dark={10:2,14:6,7:8,15:7}
        a=[dark.get(c,c) for c in a]
    return a

def main():
    import sys
    out=Path(sys.argv[1] if len(sys.argv)>1 else 'src/rd_face_art.h')
    out.write_text('/* Generated by tools/make_face_art.py. */\n'
                   'static const unsigned char rd_face_art[8][3][256]={\n'+
                   ',\n'.join('{'+','.join('{'+','.join(map(str,tile(m,f)))+'}' for f in range(3))+'}' for m in range(8))+'\n};\n')
    print('Baked 24 face textures, 6144 bytes, 16-color indices only')

if __name__=='__main__': main()
